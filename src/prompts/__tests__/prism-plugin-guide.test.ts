/**
 * Prism Plugin Guide Tests
 *
 * `PRISM_PLUGIN_TYPES` restates the contract in `services/prism-plugins/types.ts`
 * as a declaration file, because a bundled build has no `.ts` source on disk to
 * copy. Two copies of one contract drift, so this fails when a type in that file
 * has no counterpart here.
 */

import { describe, it, expect } from 'vitest';
import fs from 'fs';
import path from 'path';
import { PRISM_PLUGIN_GUIDE, PRISM_PLUGIN_TYPES } from '../prism-plugin-guide';

const CONTRACT = path.join(__dirname, '..', '..', 'services', 'prism-plugins', 'types.ts');

/** Every exported interface, type alias and field name in the contract. */
function exportedNames(source: string): string[] {
  return [...source.matchAll(/^export (?:interface|type) (\w+)/gm)].map((m) => m[1]);
}

describe('the emitted declarations', () => {
  it('declare every type the contract exports', () => {
    const contract = fs.readFileSync(CONTRACT, 'utf8');
    const missing = exportedNames(contract).filter(
      (name) => !new RegExp(`\\b${name}\\b`).test(PRISM_PLUGIN_TYPES),
    );
    expect(missing).toEqual([]);
  });

  it('declare every field of the context, which is what a plugin reads first', () => {
    const contract = fs.readFileSync(CONTRACT, 'utf8');
    const block = contract.match(/export interface PrismPluginContext \{([\s\S]*?)\n\}/);
    expect(block).not.toBeNull();
    const fields = [...block![1].matchAll(/^ {2}(\w+)[?:]/gm)].map((m) => m[1]);
    expect(fields.length).toBeGreaterThan(0);
    for (const field of fields) {
      expect(PRISM_PLUGIN_TYPES).toContain(field);
    }
  });

  it('are type-only, so nothing has to resolve them at runtime', () => {
    // A value export would make the erased import in a plugin's server a real
    // one, and there is no module at that path when the plugin runs.
    expect(PRISM_PLUGIN_TYPES).not.toMatch(/^export (?:const|function|class|default)\b/m);
  });

  it('say they are generated, so nobody edits a file the next boot overwrites', () => {
    expect(PRISM_PLUGIN_TYPES).toContain('Generated by Prism Agent');
  });
});

describe('the authoring manual', () => {
  it('names the folder layout and the manifest', () => {
    expect(PRISM_PLUGIN_GUIDE).toContain('prism-plugin.json');
    expect(PRISM_PLUGIN_GUIDE).toContain('web/page.tsx');
    expect(PRISM_PLUGIN_GUIDE).toContain('server/index.ts');
    expect(PRISM_PLUGIN_GUIDE).toContain('"apiVersion": 1');
  });

  it('states the one import a page may use', () => {
    expect(PRISM_PLUGIN_GUIDE).toContain("import host from '@prism/plugin'");
  });

  it('states the className rule, which is what a page gets wrong otherwise', () => {
    expect(PRISM_PLUGIN_GUIDE).toContain('Do not set className');
  });

  it('says a change restarts the runtime', () => {
    expect(PRISM_PLUGIN_GUIDE).toContain('restarts the runtime');
  });

  it('lists every layout component the host provides, since a page needs them', () => {
    for (const name of ['Stack', 'Row', 'Grid', 'Section', 'PageHeader']) {
      expect(PRISM_PLUGIN_GUIDE).toContain(name);
    }
  });

  it('says tool input is JSON Schema rather than zod', () => {
    expect(PRISM_PLUGIN_GUIDE).toContain('JSON Schema');
  });
});
